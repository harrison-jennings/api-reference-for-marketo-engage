/**
 * Writes dist/_headers: the response headers Cloudflare serves with the site's files.
 *
 * The Content-Security-Policy is the one Astro puts in every page's meta tag, with the hashes of the
 * pages' inline scripts, so it changes whenever they do and is copied from the build rather than
 * written by hand. As a header it covers the whole page, including the theme script that runs before
 * the meta tag (which Astro doesn't hash), so the build adds the hash of every inline script it finds.
 * It also carries frame-ancestors, which browsers ignore in a meta tag. The meta tag stays: both are
 * enforced. Every page must have the same policy, since one rule covers them all.
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(process.argv[2] || "dist");

/** A page's meta CSP, as "directive sources; directive sources". */
export function metaPolicy(html) {
  const content = html.match(/http-equiv="content-security-policy"[^>]*content="([^"]*)"/i)?.[1];
  if (!content) return null;
  return content.split(";").map((directive) => directive.trim().replace(/\s+/g, " ")).filter(Boolean).join("; ");
}

/** The hashes of a page's inline scripts, other than structured data, which browsers don't run. */
export function inlineScriptHashes(html) {
  return [...html.matchAll(/<script(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/g)]
    .filter(([, attributes]) => !/application\/ld\+json/.test(attributes))
    .map(([, , body]) => `'sha256-${crypto.createHash("sha256").update(body).digest("base64")}'`);
}

/** The header CSP: the meta policy, with every inline script's hash, plus what only a header can do. */
export function headerPolicy(meta, hashes) {
  const directives = meta.split("; ").map((directive) => {
    if (!directive.startsWith("script-src ")) return directive;
    const sources = directive.split(" ");
    return [...sources, ...[...new Set(hashes)].filter((hash) => !sources.includes(hash)).sort()].join(" ");
  });
  return `${directives.join("; ")}; frame-ancestors 'none'`;
}

export function headers(policy) {
  return `# Generated by scripts/headers.mjs after each build. Cloudflare applies these rules and doesn't serve this file.
/*
  Content-Security-Policy: ${policy}
  Strict-Transport-Security: max-age=31536000
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()
  Cross-Origin-Opener-Policy: same-origin

/_astro/*
  Cache-Control: public, max-age=31536000, immutable
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const pages = fs.readdirSync(root, { recursive: true }).filter((file) => file.endsWith(".html"));
  const policies = new Map();
  const hashes = new Set();
  for (const page of pages) {
    const html = fs.readFileSync(path.join(root, page), "utf8");
    const policy = metaPolicy(html);
    if (!policy) throw new Error(`${page}: no CSP meta tag`);
    if (!policies.has(policy)) policies.set(policy, page);
    for (const hash of inlineScriptHashes(html)) hashes.add(hash);
  }
  if (policies.size !== 1) {
    throw new Error(`Pages have ${policies.size} different CSPs, and _headers can only give them one: ${[...policies.values()].slice(0, 5).join(", ")}`);
  }
  fs.writeFileSync(path.join(root, "_headers"), headers(headerPolicy([...policies.keys()][0], [...hashes])));
  console.log(`Wrote _headers with the CSP of ${pages.length} pages.`);
}
